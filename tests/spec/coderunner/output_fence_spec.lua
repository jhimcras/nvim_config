local H = require('tests.spec.coderunner.helpers')
local blocks = require('nvim_config.coderunner.blocks')
local output = require('nvim_config.coderunner.output_fence')
local api = vim.api

describe('coderunner output fences', function()
    local root, buf, snapshot
    local function capture(text)
        buf = H.buffer(root, text)
        snapshot = output.capture(buf, assert(blocks.get(buf, root))[1])
    end
    local function text() return table.concat(api.nvim_buf_get_lines(buf, 0, -1, false), '\n') end
    before_each(function() root = H.workspace() end)
    after_each(function()
        output.clear(snapshot)
        if buf and api.nvim_buf_is_valid(buf) then api.nvim_buf_delete(buf, { force = true }) end
        vim.fn.delete(root, 'rf')
    end)
    it('inserts stdout using a fence longer than every output backtick run', function()
        capture('```python\nprint(1)\n```\n')
        assert.is_true(output.apply(snapshot, { status = 'success', stdout = 'a````b\n', stderr = 'hidden' }))
        assert.equals('```python\nprint(1)\n```\n\n`````output\na````b\n`````', text())
    end)
    it('replaces adjacent output and marks failed output', function()
        capture('```python\nx\n```\n\n```output\nold\n```\n')
        assert.is_true(output.apply(snapshot, { status = 'failed', stdout = 'new\n' }))
        assert.matches('```output {.error}\nnew\n```', text(), 1, true)
        assert.is_nil(text():find('old', 1, true))
    end)
    it('allows line movement caused by edits in other regions', function()
        capture('```python\nx\n```\n')
        api.nvim_buf_set_lines(buf, 0, 0, false, { 'heading', '' })
        assert.is_true(output.apply(snapshot, { status = 'success', stdout = 'ok' }))
        assert.matches('heading\n\n```python', text(), 1, true)
    end)
    it('rejects source and existing output edits', function()
        capture('```python\nx\n```\n\n```output\nold\n```\n')
        api.nvim_buf_set_lines(buf, 1, 2, false, { 'changed' })
        local ok, err = output.apply(snapshot, { status = 'success' })
        assert.is_false(ok); assert.matches('source changed', err)
        api.nvim_buf_set_lines(buf, 1, 2, false, { 'x' })
        api.nvim_buf_set_lines(buf, 5, 6, false, { 'changed output' })
        ok, err = output.apply(snapshot, { status = 'success' })
        assert.is_false(ok); assert.matches('output changed', err)
    end)
    it('rejects newly attached output and nonmodifiable buffers', function()
        capture('```python\nx\n```\n')
        api.nvim_buf_set_lines(buf, 3, 3, false, { '', '```output', 'someone else', '```' })
        assert.is_false(output.apply(snapshot, { status = 'success' }))
        vim.bo[buf].modifiable = false
        local ok, err = output.apply(snapshot, { status = 'success' })
        assert.is_false(ok); assert.matches('not modifiable', err)
    end)
    it('only displays container blocks and unclosed fences', function()
        capture('> ```python\n> x\n> ```\n')
        local before = text()
        assert.is_false(output.apply(snapshot, { status = 'success', stdout = 'ok' }))
        assert.equals(before, text())
    end)
    it('applies insertion as one undo step and preserves the original source', function()
        capture('```python\nx\n```\n')
        api.nvim_set_current_buf(buf)
        local before = text()
        assert.is_true(output.apply(snapshot, { status = 'success', stdout = 'ok' }))
        vim.cmd('undo')
        assert.equals(before, text())
    end)
end)
